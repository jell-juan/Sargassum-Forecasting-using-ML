import torch
import torch.nn as nn
from torch.autograd import Variable # Variable is mostly deprecated in modern PyTorch, but included for compatibility.


class ConvLSTMCell(nn.Module):
    def __init__(self, input_dim, hidden_dim, kernel_size, bias):
        """
        Initialize ConvLSTM cell.
        Parameters
        ----------
        input_dim: int
            Number of channels of input tensor.
        hidden_dim: int
            Number of channels of hidden state.
        kernel_size: (int, int)
            Size of the convolutional kernel in HxW.
        bias: bool
            Whether or not to add the bias.
        """
        super(ConvLSTMCell, self).__init__()

        self.input_dim = input_dim
        self.hidden_dim = hidden_dim

        self.kernel_size = kernel_size
        # Padding ensures output spatial dimensions match input spatial dimensions
        self.padding = kernel_size[0] // 2, kernel_size[1] // 2
        self.bias = bias

        self.conv = nn.Conv2d(in_channels=self.input_dim + self.hidden_dim,
                              out_channels=4 * self.hidden_dim, # For input, forget, output, and cell gates
                              kernel_size=self.kernel_size,
                              padding=self.padding,
                              bias=self.bias)

    def forward(self, input_tensor, cur_state):
        h_cur, c_cur = cur_state

        # Concatenate input and hidden state along the channel dimension
        combined_conv = self.conv(torch.cat([input_tensor, h_cur], dim=1))

        # Split the combined convolution output into 4 parts for i, f, o, g gates
        cc_i, cc_f, cc_o, cc_g = torch.split(combined_conv, self.hidden_dim, dim=1)

        i = torch.sigmoid(cc_i)  # Input gate
        f = torch.sigmoid(cc_f)  # Forget gate
        o = torch.sigmoid(cc_o)  # Output gate
        g = torch.tanh(cc_g)     # Candidate cell state

        c_next = f * c_cur + i * g # Next cell state
        h_next = o * torch.tanh(c_next) # Next hidden state

        return h_next, c_next

    def init_hidden(self, batch_size, image_size):
        height, width = image_size
        # Initialize hidden and cell states with zeros. Move to GPU if available.
        return (Variable(torch.zeros(batch_size, self.hidden_dim, height, width)).cuda() if torch.cuda.is_available() else
                Variable(torch.zeros(batch_size, self.hidden_dim, height, width)),
                Variable(torch.zeros(batch_size, self.hidden_dim, height, width)).cuda() if torch.cuda.is_available() else
                Variable(torch.zeros(batch_size, self.hidden_dim, height, width)))


class ConvLSTM(nn.Module):
    def __init__(self, input_dim, hidden_dim, kernel_size, num_layers,
                 batch_first=False, bias=True, return_all_layers=False):
        super(ConvLSTM, self).__init__()

        self._check_kernel_size_consistency(kernel_size)

        # Ensure hidden_dim and kernel_size are lists, even if a single value is provided
        hidden_dim = self._extend_for_multilayer(hidden_dim, num_layers)
        kernel_size = self._extend_for_multilayer(kernel_size, num_layers)

        if not len(hidden_dim) == len(kernel_size) == num_layers:
            raise ValueError('In ConvLSTM, hidden_dim and kernel_size must have the same length as num_layers')

        self.input_dim = input_dim
        self.hidden_dim = hidden_dim
        self.kernel_size = kernel_size
        self.num_layers = num_layers
        self.batch_first = batch_first
        self.bias = bias
        self.return_all_layers = return_all_layers

        cell_list = []
        for i in range(self.num_layers):
            # The input dimension for the first layer is `input_dim`, for subsequent layers it's the `hidden_dim` of the previous layer
            cur_input_dim = self.input_dim if i == 0 else self.hidden_dim[i-1]
            cell_list.append(ConvLSTMCell(input_dim=cur_input_dim,
                                          hidden_dim=self.hidden_dim[i],
                                          kernel_size=self.kernel_size[i],
                                          bias=self.bias))
        self.cell_list = nn.ModuleList(cell_list)

    def forward(self, input_tensor, hidden_state=None):
        """
        Parameters
        ----------
        input_tensor: 5-D Tensor
            Expected input tensor shape:
            (batch_size, seq_len, input_dim, image_width, image_height) if `batch_first` is True.
            (seq_len, batch_size, input_dim, image_width, image_height) if `batch_first` is False.

            Based on your prior notes, `X = (batch, sequence, channels, lat, lon)` suggests `batch_first=True`
            where:
            - `batch` -> `batch_size`
            - `sequence` -> `seq_len`
            - `channels` -> `input_dim` (number of features per spatial location)
            - `lat` -> `image_width` (or height)
            - `lon` -> `image_height` (or width)

        hidden_state: list of tuples, optional
            Initial hidden and cell states for each layer. If None, states are initialized to zeros.

        Returns
        -------
        last_state_list: list of tuples
            (h, c) for each layer at the last time step.
        layer_output: list of Tensors
            Output hidden states for each layer at each time step (if `return_all_layers` is True),
            or only the last layer's outputs (if `return_all_layers` is False).
        """
        if not self.batch_first: # Adjust dimensions if batch_first is False
            # (seq_len, batch_size, input_dim, H, W) -> (batch_size, seq_len, input_dim, H, W)
            input_tensor = input_tensor.permute(1, 0, 2, 3, 4)

        b, seq_len, _, h_spatial, w_spatial = input_tensor.size()

        # Initialize hidden state and cell state for all layers if not provided
        if hidden_state is None:
            hidden_state = self._init_hidden(batch_size=b, image_size=(h_spatial, w_spatial))

        # Check if GPU is available and move tensors to GPU
        if torch.cuda.is_available():
            input_tensor = input_tensor.cuda()

        layer_output_list = []
        last_state_list = []

        cur_layer_input = input_tensor

        for layer_idx in range(self.num_layers):
            h, c = hidden_state[layer_idx]
            output_inner = []
            for t in range(seq_len):
                # Pass input for current time step and current hidden state to the ConvLSTM cell
                h, c = self.cell_list[layer_idx](input_tensor=cur_layer_input[:, t, :, :, :], cur_state=[h, c])
                output_inner.append(h)

            layer_output = torch.stack(output_inner, dim=1) # Stack outputs along the sequence dimension
            cur_layer_input = layer_output # Output of current layer becomes input for the next layer

            layer_output_list.append(layer_output)
            last_state_list.append([h, c])

        if not self.return_all_layers: # Return only the last layer's final state and all its sequence outputs
            return last_state_list[-1], layer_output_list[-1]
        else: # Return final states and all sequence outputs for all layers
            return last_state_list, layer_output_list

    def _init_hidden(self, batch_size, image_size):
        # Helper to initialize hidden states for all layers
        init_states = []
        for i in range(self.num_layers):
            init_states.append(self.cell_list[i].init_hidden(batch_size, image_size))
        return init_states

    @staticmethod
    def _check_kernel_size_consistency(kernel_size):
        # Ensures kernel_size is a tuple or a list of tuples
        if not (isinstance(kernel_size, tuple) or
                (isinstance(kernel_size, list) and all([isinstance(elem, tuple) for elem in kernel_size]))):
            raise ValueError('kernel_size must be tuple or list of tuples')

    @staticmethod
    def _extend_for_multilayer(param, num_layers):
        # Helper to ensure parameters are lists for multi-layer configuration
        if not isinstance(param, list):
            param = [param] * num_layers
        return param


