"""### Res U-net Architecture Implementation

This section implements a basic Res U-net architecture using PyTorch. The key components are:

*   **Residual Blocks**: Used in both the encoder and decoder paths to facilitate learning by allowing information to bypass some layers.
*   **Encoder Path**: Consists of several downsampling steps (e.g., using `MaxPool2d` or strided convolutions) combined with residual blocks, reducing spatial dimensions and increasing channel depth.
*   **Bottleneck**: The lowest resolution part of the network, typically a residual block.
*   **Decoder Path**: Consists of several upsampling steps (e.g., `ConvTranspose2d` or `Upsample` followed by `Conv2d`) combined with residual blocks. Skip connections from the encoder path are concatenated here to provide high-resolution feature maps.
*   **Output Layer**: A final convolution to map to the desired number of output channels.

As per your notes, the expected input shape for the Res U-net is `(time, channels, lat, lon)`. In PyTorch, this often translates to `(batch_size, channels, height, width)`, where `time` acts as the `batch_size` for individual images or frames.
"""

import torch
import torch.nn as nn
import torch.nn.functional as F


class ResidualBlock(nn.Module):
    def __init__(self, in_channels, out_channels, stride=1, downsample=None):
        super(ResidualBlock, self).__init__()
        self.conv1 = nn.Conv2d(in_channels, out_channels, kernel_size=3, stride=stride, padding=1, bias=False)
        self.bn1 = nn.BatchNorm2d(out_channels)
        self.relu = nn.ReLU(inplace=True)
        self.conv2 = nn.Conv2d(out_channels, out_channels, kernel_size=3, stride=1, padding=1, bias=False)
        self.bn2 = nn.BatchNorm2d(out_channels)
        self.downsample = downsample

    def forward(self, x):
        residual = x
        out = self.conv1(x)
        out = self.bn1(out)
        out = self.relu(out)
        out = self.conv2(out)
        out = self.bn2(out)
        if self.downsample is not None:
            residual = self.downsample(x)
        out += residual
        out = self.relu(out)
        return out


class ResUNet(nn.Module):
    def __init__(self, in_channels, out_channels, features=[64, 128, 256, 512]):
        super(ResUNet, self).__init__()
        self.in_channels = in_channels
        self.out_channels = out_channels

        self.encoder_blocks = nn.ModuleList()
        self.decoder_blocks = nn.ModuleList()

        # Initial Convolution
        self.initial_conv = nn.Sequential(
            nn.Conv2d(in_channels, features[0], kernel_size=3, padding=1, bias=False),
            nn.BatchNorm2d(features[0]),
            nn.ReLU(inplace=True)
        )

        # Encoder (Downsampling path)
        current_in_channels = features[0]
        for i, feature in enumerate(features):
            downsample = None
            # This block is for handling channel mismatch for residual connection if stride changes or if it's the first block
            if i == 0 or current_in_channels != feature:
                 downsample = nn.Sequential(
                    nn.Conv2d(current_in_channels if i > 0 else in_channels, feature, kernel_size=1, stride=2, bias=False) if i > 0 else nn.Identity(), # For first block, use Identity for initial conv channels
                    nn.BatchNorm2d(feature) if i > 0 else nn.Identity()
                 )

            self.encoder_blocks.append(nn.Sequential(
                ResidualBlock(current_in_channels, feature, stride=1),
                nn.MaxPool2d(kernel_size=2, stride=2)
            ))
            current_in_channels = feature


        # Bottleneck
        self.bottleneck = ResidualBlock(features[-1], features[-1] * 2, stride=1)

        # Decoder (Upsampling path)
        for i in reversed(range(len(features))):
            feature = features[i]
            # ConvTranspose2d to upsample
            self.decoder_blocks.append(nn.Sequential(
                nn.ConvTranspose2d(feature * 2 if i == len(features) - 1 else feature * 2, feature, kernel_size=2, stride=2),
                ResidualBlock(feature * 2, feature) # Concatenate skip connection, so input channels are doubled
            ))

        # Final output layer
        self.final_conv = nn.Conv2d(features[0], out_channels, kernel_size=1)

    def forward(self, x):
        skip_connections = []

        # Initial Convolution
        x = self.initial_conv(x)
        # No MaxPool after initial_conv, so first skip connection is 'x' itself
        skip_connections.append(x)

        # Encoder
        for block in self.encoder_blocks:
            x = block(x)
            skip_connections.append(x)

        # The last element in skip_connections is the input to the bottleneck (after the last encoder block's MaxPool)
        # We will pop it when we start the decoder path, as it's the connection to the first upsampling.

        # Bottleneck
        x = self.bottleneck(skip_connections.pop()) # Use the input to the bottleneck from skip_connections

        # Decoder
        for i, block in enumerate(self.decoder_blocks):
            # Upsample (ConvTranspose2d part)
            x = block[0](x)

            # Retrieve corresponding skip connection
            skip_x = skip_connections.pop()

            # Handle potential size mismatches (e.g., if input image size is not perfectly divisible)
            if x.shape[2:] != skip_x.shape[2:]:
                x = F.interpolate(x, size=skip_x.shape[2:], mode='bilinear', align_corners=False)

            # Concatenate skip connection along the channel dimension
            x = torch.cat([x, skip_x], dim=1)

            # Apply the residual block after concatenation
            x = block[1](x)

        return self.final_conv(x)


