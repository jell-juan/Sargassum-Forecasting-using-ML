"""
results_dashboard.py

A presentation-ready results dashboard that needs NONE of the trained
model files (.joblib, .pth) and does NO live inference or network calls --
only the small output ARTIFACTS your training runs already produced:

    model_comparison_results.csv   (from ml_training_pipeline_budgeted.py)
    best_model_params.json         (from ml_training_pipeline_budgeted.py)
    train_test_metrics.png         (from ml_training_pipeline_budgeted.py)
    convlstm_loss_curve.png        (from train.py, optional)

All are tiny (KB to a few hundred KB) -- trivial to move by any method,
unlike the model binaries this avoids needing entirely.

Every section checks whether its file actually exists before trying to
show it, so this runs fine even if you only have some of the four files
on this laptop -- missing ones show a plain "not available" message
instead of crashing.

Run with:
    streamlit run results_dashboard.py
Needs only: pip install streamlit pandas pillow
(no torch, xgboost, joblib, or xarray required for this dashboard)
"""

import json
from pathlib import Path

import pandas as pd
import streamlit as st
from PIL import Image

BASE_DIR = Path(__file__).resolve().parent
RESULTS_CSV = BASE_DIR / "model_comparison_results.csv"
BEST_PARAMS_JSON = BASE_DIR / "best_model_params.json"
TRAIN_TEST_PNG = BASE_DIR / "train_test_metrics.png"
CONVLSTM_LOSS_PNG = BASE_DIR / "convlstm_loss_curve.png"


def section(title):
    st.header(title)


def missing(path: Path):
    st.info(f"`{path.name}` not found in this folder -- copy it over from the training machine to show this section.")


def main():
    st.set_page_config(page_title="Sargassum Forecasting -- Results", layout="wide")
    st.title("Sargassum Forecasting: Model Comparison Results")
    st.caption("Results-only dashboard -- displays pre-computed outputs, no live model loading or inference.")

    # --- Model comparison table ---
    section("Model Comparison (Test Set)")
    if RESULTS_CSV.exists():
        results_df = pd.read_csv(RESULTS_CSV)
        test_df = results_df[results_df["Split"] == "test"].sort_values("RMSE")
        st.dataframe(test_df.reset_index(drop=True), width="stretch")

        with st.expander("Show train split too"):
            train_df = results_df[results_df["Split"] == "train"].sort_values("RMSE")
            st.dataframe(train_df.reset_index(drop=True), width="stretch")
    else:
        missing(RESULTS_CSV)

    st.divider()

    # --- Train vs test metrics chart (pre-generated by the training script) ---
    section("Training vs Testing Metrics")
    if TRAIN_TEST_PNG.exists():
        st.image(Image.open(TRAIN_TEST_PNG), width="stretch")
    else:
        missing(TRAIN_TEST_PNG)

    st.divider()

    # --- Best hyperparameters found per model ---
    section("Best Hyperparameters (from grid/randomized search)")
    if BEST_PARAMS_JSON.exists():
        with open(BEST_PARAMS_JSON) as f:
            best_params = json.load(f)
        cols = st.columns(len(best_params)) if best_params else [st]
        for col, (model_name, params) in zip(cols, best_params.items()):
            with col:
                st.subheader(model_name)
                st.json(params)
    else:
        missing(BEST_PARAMS_JSON)

    st.divider()

    # --- ConvLSTM training curve (optional -- separate pipeline) ---
    section("ConvLSTM Training Curve")
    if CONVLSTM_LOSS_PNG.exists():
        st.image(Image.open(CONVLSTM_LOSS_PNG), width="stretch")
    else:
        missing(CONVLSTM_LOSS_PNG)


if __name__ == "__main__":
    main()